#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""convert.py — regenerate evals/evals.json from the source-of-truth eval files.

`trigger_evals.json` and `output_quality_evals.json` ARE the source of truth.
`evals.json` is GENERATED and must never be hand-edited: a hand-edit is silently lost the
next time this runs, which is the worst possible failure mode for a routing test.

Run it after every change to either source file.

Usage:
    convert.py            # regenerate evals.json
    convert.py --check    # exit nonzero if evals.json is stale (CI)
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
BANNER = ("GENERATED BY evals/convert.py — DO NOT HAND-EDIT. Edit trigger_evals.json or "
          "output_quality_evals.json and re-run convert.py.")


def build():
    trig = json.loads((HERE / "trigger_evals.json").read_text(encoding="utf-8"))
    qual = json.loads((HERE / "output_quality_evals.json").read_text(encoding="utf-8"))

    cases = []
    for item in trig["should_trigger"]:
        cases.append({"id": "trigger/{}".format(len(cases) + 1),
                      "kind": "routing", "prompt": item["prompt"],
                      "expect": {"skill": trig["skill"], "triggers": True},
                      "note": item["note"]})
    for item in trig["should_not_trigger"]:
        cases.append({"id": "trigger/{}".format(len(cases) + 1),
                      "kind": "routing", "prompt": item["prompt"],
                      "expect": {"skill": trig["skill"], "triggers": False,
                                 "route_to": item.get("expected_route")},
                      "note": item["note"]})
    for axis in qual["axes"]:
        cases.append({"id": "quality/{}".format(axis["id"]),
                      "kind": "output_quality",
                      "assert": axis["assert"], "why": axis["why"],
                      "enforced_by": axis["check"]})

    return {"_generated": BANNER, "skill": trig["skill"],
            "counts": {"should_trigger": len(trig["should_trigger"]),
                       "should_not_trigger": len(trig["should_not_trigger"]),
                       "quality_axes": len(qual["axes"]),
                       "total": len(cases)},
            "cases": cases}


def main(argv=None):
    ap = argparse.ArgumentParser(
        prog="convert.py",
        description="Regenerate evals/evals.json from trigger_evals.json and "
                    "output_quality_evals.json. Never hand-edit evals.json.")
    ap.add_argument("--check", action="store_true",
                    help="exit nonzero if evals.json is stale rather than rewriting it")
    args = ap.parse_args(argv)

    doc = build()
    out = HERE / "evals.json"
    text = json.dumps(doc, indent=2, ensure_ascii=False) + "\n"

    if args.check:
        current = out.read_text(encoding="utf-8") if out.is_file() else ""
        if current != text:
            print("evals.json is STALE — run: python3 evals/convert.py", file=sys.stderr)
            return 1
        print("evals.json is current ({} cases)".format(doc["counts"]["total"]))
        return 0

    out.write_text(text, encoding="utf-8")
    c = doc["counts"]
    print("wrote {}".format(out))
    print("  {} should-trigger (min 14), {} should-not-trigger (min 13), {} quality axes"
          .format(c["should_trigger"], c["should_not_trigger"], c["quality_axes"]))
    if c["should_trigger"] < 14 or c["should_not_trigger"] < 13:
        print("  WARNING: below the required minimums", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
